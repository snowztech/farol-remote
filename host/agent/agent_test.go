func logFile(t *testing.T, lines []string) *Transcript {
	t.Helper()
	path := filepath.Join(t.TempDir(), "log.jsonl")
	if err := os.WriteFile(path, []byte(strings.Join(lines, "\n")+"\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	return &Transcript{Path: path}
}

func appendTo(t *testing.T, path, text string) {
	t.Helper()
	file, err := os.OpenFile(path, os.O_APPEND|os.O_WRONLY, 0)
	if err != nil {
		t.Fatal(err)
	}
	defer file.Close()
	file.WriteString(text)
}

func roles(messages []Message) []Role {
	list := []Role{}
	for _, message := range messages {
		list = append(list, message.Role)
	}
	return list
}

func texts(messages []Message) []string {
	list := []string{}
	for _, message := range messages {
		list = append(list, message.Text)
	}
	return list
}

func TestReadsTheConversationAndSkipsTheRest(t *testing.T) {
	transcript := logFile(t, claudeLines)
	if !transcript.Refresh() {
		t.Fatal("nothing read")
	}
	messages := transcript.Messages()
	if got := roles(messages); !reflect.DeepEqual(got, []Role{You, Agent, Tool, Tool}) {
		t.Fatalf("roles %v", got)
	}
	want := []Message{
		{ID: "u1.0", Role: You, Text: "the order test fails one run in ten"},
		{ID: "a1.1", Role: Agent, Text: "The test compares two links saved in the same millisecond."},
		{ID: "a2.0", Role: Tool, Text: "Run the tests", Tool: "Bash", Detail: "npm test"},
		{ID: "a3.0", Role: Tool, Text: "tests/store.test.ts", Tool: "Edit", Detail: "@@\n-await sleep(1)\n+const clock = fixedClock()\n+const store = createStore({ clock })\n"},
	}
	if !reflect.DeepEqual(messages, want) {
		t.Fatalf("read %+v", messages)
	}
}

func TestReadsOnlyWhatWasAdded(t *testing.T) {
	transcript := logFile(t, claudeLines[:2])
	if !transcript.Refresh() || len(transcript.Messages()) != 1 || transcript.Refresh() {
		t.Fatal("the first read")
	}
	// Half a line, as an agent that is still writing leaves it, then the rest.
	line := claudeLines[4] + "\n"
	appendTo(t, transcript.Path, line[:40])
	if transcript.Refresh() {
		t.Fatal("half a line changed the messages")
	}
	appendTo(t, transcript.Path, line[40:])
	if !transcript.Refresh() || !reflect.DeepEqual(roles(transcript.Messages()), []Role{You, Agent}) {
		t.Fatalf("read %+v", transcript.Messages())
	}
}

