func TestLeavesOutWhatARewindReplaced(t *testing.T) {
	transcript := logFile(t, []string{
		`{"parentUuid":null,"type":"user","uuid":"p1","message":{"role":"user","content":"read the store"}}`,
		// Two reads side by side, each answered under its own call.
		`{"parentUuid":"p1","type":"assistant","uuid":"r1","message":{"role":"assistant","content":[{"type":"tool_use","name":"Read","input":{"file_path":"/a.ts"}}]}}`,
		`{"parentUuid":"r1","type":"assistant","uuid":"r2","message":{"role":"assistant","content":[{"type":"tool_use","name":"Read","input":{"file_path":"/b.ts"}}]}}`,
		`{"parentUuid":"r2","type":"user","uuid":"t2","message":{"role":"user","content":[{"type":"tool_result","content":"b"}]}}`,
		`{"parentUuid":"r1","type":"user","uuid":"t1","message":{"role":"user","content":[{"type":"tool_result","content":"a"}]}}`,
		`{"parentUuid":"t2","type":"assistant","uuid":"a1","message":{"role":"assistant","content":[{"type":"text","text":"Both read."}]}}`,
		`{"parentUuid":"a1","type":"user","uuid":"p2","message":{"role":"user","content":"delete them"}}`,
		`{"parentUuid":"p2","type":"assistant","uuid":"a2","message":{"role":"assistant","content":[{"type":"text","text":"Deleted."}]}}`,
		// You rewound to before "delete them" and asked something else.
		`{"parentUuid":"a1","type":"user","uuid":"p3","message":{"role":"user","content":"keep them"}}`,
	})
	transcript.Refresh()
	if got := texts(transcript.Messages()); !reflect.DeepEqual(got, []string{"read the store", "/a.ts", "/b.ts", "Both read.", "keep them"}) {
		t.Fatalf("read %v", got)
	}
	// The agent's answer to a rewound prompt, written late, stays out too.
	appendTo(t, transcript.Path, `{"parentUuid":"a2","type":"assistant","uuid":"a3","message":{"role":"assistant","content":[{"type":"text","text":"Also gone."}]}}`+"\n")
	transcript.Refresh()
	if got := texts(transcript.Messages()); got[len(got)-1] != "keep them" {
		t.Fatalf("read %v", got)
	}
}

